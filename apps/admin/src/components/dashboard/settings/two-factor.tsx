"use client";

import { useState, useTransition } from "react";
import type { TwoFactorResult, TwoFactorSetup } from "@/app/app/[tenant]/settings/account/actions";
import { Button } from "@/components/ui/button";
import { Field } from "@/components/ui/field";
import { Input } from "@/components/ui/input";
import { toast } from "@/components/ui/toast";

// Settings → Account. Off: scan a code, then prove it worked. On: a code from
// the app turns it off, so an unattended laptop can't.
export function TwoFactor({
  enabled,
  start,
  confirm,
  disable,
}: {
  enabled: boolean;
  start: () => Promise<{ setup?: TwoFactorSetup; error?: string }>;
  confirm: (factorId: string, code: string) => Promise<TwoFactorResult>;
  disable: (code: string) => Promise<TwoFactorResult>;
}) {
  const [setup, setSetup] = useState<TwoFactorSetup | null>(null);
  const [turningOff, setTurningOff] = useState(false);
  const [code, setCode] = useState("");
  const [error, setError] = useState<string>();
  const [pending, startTransition] = useTransition();

  function reset() {
    setSetup(null);
    setTurningOff(false);
    setCode("");
    setError(undefined);
  }

  function begin() {
    startTransition(async () => {
      setError(undefined);
      const result = await start();
      if (result.setup) setSetup(result.setup);
      else setError(result.error);
    });
  }

  function submit(event: React.FormEvent) {
    event.preventDefault();
    startTransition(async () => {
      setError(undefined);
      const result = setup ? await confirm(setup.factorId, code) : await disable(code);
      if (result.error) {
        setError(result.error);
        return;
      }
      toast.success(setup ? "Two-factor login is on" : "Two-factor login is off");
      reset();
    });
  }

  const codeField = (
    <Field label="6-digit code from the app" name="code" error={error}>
      <Input
        id="code"
        name="code"
        inputMode="numeric"
        autoComplete="one-time-code"
        maxLength={7}
        className="max-w-40"
        value={code}
        onChange={(e) => setCode(e.target.value)}
      />
    </Field>
  );
  const actions = (label: string, danger = false) => (
    <div className="flex flex-wrap gap-2 border-t pt-4">
      <Button type="submit" size="lg" variant={danger ? "destructive" : "default"} disabled={pending}>
        {pending ? "Checking…" : label}
      </Button>
      <Button type="button" variant="ghost" size="lg" onClick={reset} disabled={pending}>
        Cancel
      </Button>
    </div>
  );

  if (setup) {
    return (
      <form onSubmit={submit} className="grid gap-4">
        <p>Scan this with an authenticator app such as Google Authenticator, Microsoft Authenticator or 1Password.</p>
        {/* A QR code generated by Supabase for this person, as an inline image. */}
        {/* eslint-disable-next-line @next/next/no-img-element */}
        <img src={setup.qr} alt="QR code to scan with your authenticator app" className="size-44 rounded-lg bg-white p-2" />
        <p className="text-sm text-muted-foreground">
          Can&apos;t scan it? Enter this key instead: <code className="break-all font-mono text-foreground">{setup.secret}</code>
        </p>
        {codeField}
        {actions("Turn on")}
      </form>
    );
  }

  if (turningOff) {
    return (
      <form onSubmit={submit} className="grid gap-4">
        <p>Enter a code from your authenticator app to turn it off. Your account is then protected by your password alone.</p>
        {codeField}
        {actions("Turn off two-factor login", true)}
      </form>
    );
  }

  return (
    <div className="grid gap-2">
      {error && (
        <p role="alert" className="text-sm text-destructive">
          {error}
        </p>
      )}
      <div>
        {enabled ? (
          <Button type="button" variant="destructive" size="lg" onClick={() => setTurningOff(true)}>
            Turn off
          </Button>
        ) : (
          <Button type="button" size="lg" onClick={begin} disabled={pending}>
            {pending ? "Starting…" : "Set up two-factor login"}
          </Button>
        )}
      </div>
    </div>
  );
}
